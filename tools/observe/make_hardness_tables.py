#!/usr/bin/env python3
"""Interim soft-tip tables for hardness levels 1-4 (spec B-009), from our own observations
(pure Python + Pillow). Writes crates/brushye-core/src/brush/hardness_tables.rs.

Each export B009_h<L>_aa0.png holds one size-101 dab. The soft dab is centred on the pixel
corner (301, 201), half a pixel from the press point (300.5, 200.5): its +x profile at pixel i
equals the -x profile at pixel i-1. Every pixel is binned by its distance to that centre in
STEP px bins; a bin's value is the mean alpha. Empty bins are linearly filled. Values are
stored in 1/256 alpha units (u16). The engine scales distances by 50.5/R. This is an interim
model until the exact falloff is observed (B-009 open questions).

usage: make_hardness_tables.py DATA_DIR OUT.rs
"""
import math
import sys

from PIL import Image

CX, CY = 301.0, 201.0
STEP = 0.25
N = int(76 / STEP) + 1


def table(path):
    a = Image.open(path).getchannel("A")
    sums, counts = [0.0] * N, [0] * N
    for y in range(120, 282):
        for x in range(220, 382):
            d = math.hypot(x + 0.5 - CX, y + 0.5 - CY)
            i = round(d / STEP)
            if i < N:
                sums[i] += a.getpixel((x, y))
                counts[i] += 1
    vals = [s / c if c else None for s, c in zip(sums, counts)]
    known = [i for i, v in enumerate(vals) if v is not None]
    for i, v in enumerate(vals):
        if v is None:
            lo = max((k for k in known if k < i), default=known[0])
            hi = min((k for k in known if k > i), default=known[-1])
            vals[i] = vals[lo] if lo == hi else vals[lo] + (vals[hi] - vals[lo]) * (i - lo) / (hi - lo)
    return [min(255 * 256, round(v * 256)) for v in vals]


def main():
    d, out = sys.argv[1], sys.argv[2]
    lines = [
        "//! Generated by tools/observe/make_hardness_tables.py from specs/behavior/brush/data/B009_h*_aa0.png.",
        "//! Interim soft-tip profiles (spec B-009): alpha × 256 at distance i × STEP px from the",
        "//! centre of a size-101 dab (R = 50.5). Do not edit by hand.",
        "",
        f"pub const STEP: f64 = {STEP};",
        "pub const REF_RADIUS: f64 = 50.5;",
        "",
        f"pub static PROFILES: [[u16; {N}]; 4] = [",
    ]
    for lvl in range(1, 5):
        t = table(f"{d}/B009_h{lvl}_aa0.png")
        lines.append("    [")
        for i in range(0, N, 16):
            lines.append("        " + ", ".join(str(v) for v in t[i:i + 16]) + ",")
        lines.append("    ],")
    lines.append("];")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
