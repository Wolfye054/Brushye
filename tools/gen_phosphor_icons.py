#!/usr/bin/env python3
"""Generate crates/brushye-app/src/icons.rs from Phosphor's style.css (npm @phosphor-icons/web).

usage: gen_phosphor_icons.py PATH/TO/regular/style.css OUT.rs
Each `.ph.ph-<name>:before { content: "\\e123"; }` becomes `pub const <NAME>: &str = "\\u{e123}";`.
The regular and fill fonts share code points, so one table serves both.
"""
import re
import sys

css, out = sys.argv[1], sys.argv[2]
pairs = re.findall(r'\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"', open(css).read())
lines = [
    "//! Phosphor Icons 2.1.2 code points (MIT, assets/fonts/LICENSE-Phosphor.txt).",
    "//! Generated by tools/gen_phosphor_icons.py from @phosphor-icons/web regular/style.css. Do not edit.",
    "#![allow(dead_code)]",
    "",
]
seen = set()
for name, cp in pairs:
    ident = name.upper().replace("-", "_")
    if ident[0].isdigit():
        ident = "N" + ident
    if ident in seen:
        continue
    seen.add(ident)
    lines.append(f'pub const {ident}: &str = "\\u{{{cp}}}";')
open(out, "w").write("\n".join(lines) + "\n")
print(len(seen), "icons")
